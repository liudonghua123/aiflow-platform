export function t(zh, ...args) {
  let s = current === 'zh' ? zh : (EN[zh] ?? zh)
  args.forEach((a, i) => { s = s.replaceAll(`{${i}}`, String(a)) })
  return s
}

// 同步 <html lang>，供日期格式化等使用
export function applyHtmlLang() {
  document.documentElement.lang = current === 'zh' ? 'zh' : 'en'
}
